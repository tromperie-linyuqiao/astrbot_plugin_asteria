_CHARACTER_NAMES = ("拉普", "能天", "大帝", "茶茶子")


class PersonaModulesMixin:
    """人格门控模块。"""

    def _persona_modules_text(self, user: dict[str, Any], event: Any = None) -> list[tuple[str, str]]:
        """返回 [(key, text)]，按门控决定加载哪些模块。"""
        packs: list[tuple[str, str]] = []
        try:
            text = str(getattr(event, "message_str", "") or "")
        except Exception:
            text = str(user.get("last_user_message") or "")
        compact = text.strip()
        intent = user.get("intent_profile") if isinstance(user.get("intent_profile"), dict) else {}
        emotion = str(intent.get("emotion") or "neutral")
        hour = self._environment_now().hour
        # 解码包：非琐碎消息即加载（纯表情/极短可跳过）
        if len(compact) > 4:
            packs.append(("persona.decode", DECODE_PACK))
        # 旁白包：情绪时刻 / 深夜 / 长文
        if emotion not in ("neutral", "") or hour >= 22 or hour <= 5 or len(compact) > 60:
            packs.append(("persona.narration", NARRATION_PACK))
        # 角色包：名字命中
        if any(name in compact for name in _CHARACTER_NAMES):
            packs.append(("persona.characters", CHARACTERS_PACK))
        return packs
